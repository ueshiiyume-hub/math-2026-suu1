def sol5(x, y, a, b, c, mid, last):
    mb = str(-b).replace('-', M)
    d4 = 4 * a * c
    inner = f"{b * b} − {d4}" if d4 >= 0 else f"{b * b} + {-d4}"
    first = ['x = ', F([mb + ' ± ', R(inner)], str(2 * a)), '   = ', mid]
    return lines(pg, [first] + last, x, y, 12, gap=8)

